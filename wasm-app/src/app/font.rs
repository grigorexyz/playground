//! A minimal hand-authored 5x7 dot-matrix bitmap font, used so the entire
//! desktop (window chrome, taskbar, card faces, log entries...) can be
//! drawn as plain GPU quads with no HTML/CSS text, canvas 2D text APIs or
//! third-party font/text-shaping crates.
//!
//! Only uppercase letters, digits and a handful of punctuation marks are
//! defined; unsupported characters fall back to a blank glyph. Rendered
//! strings are upper-cased by [`glyph_rows`]'s caller ([`crate::painter`]).

